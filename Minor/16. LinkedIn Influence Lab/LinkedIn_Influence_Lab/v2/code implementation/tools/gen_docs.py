"""Regenerates docs/03_PROJECT_STRUCTURE_GUIDE.md and docs/05_TRACEABILITY_24_PARTS.md from the code.
Run:  python tools/gen_docs.py   (keeps the docs honest when files move)"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from lil.folder_map import FOLDER_PURPOSE  # noqa: E402
from lil.paths import DELIVERABLES, PHASES  # noqa: E402
from lil.trace import TRACE  # noqa: E402

SKIP = {".venv", "__pycache__", ".pytest_cache", ".git"}
RUNTIME = {"phases", "deliverables", "backups", "logs"}


def tree(root: Path, prefix="", depth=0):
    lines = []
    for p in sorted(root.iterdir(), key=lambda x: (x.is_file(), x.name)):
        if p.name in SKIP or p.suffix == ".pyc" or p.name in ("plugins.json", "profile.json", "status.json") and "data" in str(p):
            continue
        lines.append(f"{prefix}{p.name}{'/' if p.is_dir() else ''}")
        if p.is_dir() and not (p.name in RUNTIME and depth == 0 and False):
            lines += tree(p, prefix + "    ", depth + 1)
    return lines


def structure():
    out = ["# Project Structure Guide (what is kept where)", "",
           "Use this when debugging or extending the project. Generated by `tools/gen_docs.py`; run it again after moving files.", "",
           "## 1. Folder tree", "```", ROOT.name + "/"]
    out += ["    " + l for l in tree(ROOT)]
    out += ["```", "", "## 2. What each item is for", "", "| Path | Purpose |", "|---|---|"]
    out += [f"| `{k}` | {v} |" for k, v in FOLDER_PURPOSE.items()]
    out += ["", "## 3. Phase folders and deliverable folders", "", "| Phase | Folder | Written by |", "|---|---|---|"]
    out += [f"| {p['n']}. {p['title']} ({p['week']}) | `phases/{p['folder']}/` | `pipeline.run_phase{p['n']}` |" for p in PHASES]
    out += ["", "| Deliverable set | Folder |", "|---|---|"] + [f"| {k} | `deliverables/{v}/` |" for k, v in DELIVERABLES.items()]
    out += ["", "## 4. Debugging cheat-sheet", "",
            "1. Read `logs/lil.log` (AI fallbacks, backups, failures).",
            "2. Check `data/state/status.json` for the phase states and notes.",
            "3. Open the phase's JSON in `phases/`: these are the inputs to the next step.",
            "4. Reproduce in isolation: `LIL_HOME=/tmp/x python -m pytest tests -k name`.",
            "5. To add a feature: content in `knowledge.py`, logic in an engine module, orchestration in `pipeline.py`, page in `ui/`, test in `tests/`.",
            "6. Secrets live only in `data/inputs/plugins.json`; never commit or share that file.", ""]
    return "\n".join(out)


def trace():
    out = ["# Traceability: the 24 parts of the project brief", "",
           "| # | Brief section | How it is covered | Where |", "|---|---|---|---|"]
    out += [f"| {n} | {name} | {how} | {', '.join('`' + f + '`' for f in files)} |" for n, name, how, files in TRACE]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    (ROOT / "docs" / "03_PROJECT_STRUCTURE_GUIDE.md").write_text(structure(), encoding="utf-8")
    (ROOT / "docs" / "05_TRACEABILITY_24_PARTS.md").write_text(trace(), encoding="utf-8")
    print("docs regenerated")
